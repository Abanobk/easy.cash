function selectKnowledge(full: string, question?: string): string {
  const blocks = full.split(/\n(?==== )/).map((b) => b.trim()).filter(Boolean);
  if (!question || question.trim().length < 4) {
    const prefer = /هوية المنتج|مفاهيم عامة|أسلوب الإجابة|دور المساعد كمرجع|مرجع تكلفة الاستيراد|مرجع جمركي|قائمة مراجعة|مكتب المحاسبة|ميزان المراجعة/;
    const core = blocks.filter((b) => prefer.test((b.match(/^===\s*(.+?)\s*===/) || [, ""])[1]));
    if (core.length >= 4) return core.join("\n\n").trim();
    return full.trim();
  }

  const q = question.toLowerCase();
  const always = /هوية المنتج|مفاهيم عامة|أسلوب الإجابة|دور المساعد كمرجع|دورة المستند|مكتب المحاسبة الافتراضي/;
  const forceImport = /شحن|جمرك|تكليف|نولون|تخزين|cbm|thc|oca|وصول|تكلف/i.test(question);
  const forceCalc = /حساب|محاسب|جمرك|ضريب|تكلف|صرف|توزيع|وصول|نسب|وعاء|cif|fob|vat|مطلوب|متوسط|قطعه|قطعة|راجع|صح ولا|اقتراح|مراجع|خطر|قيد|ذمم|شيك|ميزان|مراجع/i.test(question);

  const scored = blocks.map((block) => {
    const title = (block.match(/^===\s*(.+?)\s*===/) || [, ""])[1];
    if (always.test(title)) return { block, score: 100 };
    if (forceImport && /تكليف شحنة|مرجع تكلفة|مرجع جمركي|مرجع توزيع|مرجع عرض الشحن|قائمة مراجعة|أمثلة رقمية/.test(title)) {
      return { block, score: 92 };
    }
    if (forceCalc && /مرجع|تكلفة الاستيراد|جمركي|توزيع|أمثلة|قائمة مراجعة|ضريبة وفواتير|مكتب المحاسبة|ميزان المراجعة|دليل الحسابات|دورة المبيعات|دورة المشتريات|تقارير ختامية|إقفال الفترة/.test(title)) {
      return { block, score: 90 };
    }
    const hay = block.toLowerCase();
    let score = 0;
    for (const token of q.split(/[^\p{L}\p{N}]+/u).filter((t) => t.length >= 3)) {
      if (hay.includes(token)) score += 2;
      if (title.toLowerCase().includes(token)) score += 4;
    }
    return { block, score };
  });

  const picked = scored.filter((s) => s.score > 0).sort((a, b) => b.score - a.score);
  if (picked.length < 3) return full.trim();
  const chosen = new Set(picked.slice(0, 14).map((s) => s.block));
  for (const s of scored) {
    if (s.score >= 90) chosen.add(s.block);
  }
  return [...chosen].join("\n\n").trim();
}

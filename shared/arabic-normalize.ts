/**
 * توحيد نصوص عربية للمقارنة/البحث: بيشيل التشكيل والتطويل، ويوحّد صور الألف
 * والياء/الألف المقصورة والتاء المربوطة/الهاء، عشان "احمد" و"أحمد" و"محمد الهضة"
 * و"محمد الهضه" كلهم يتطابقوا في البحث بدل ما يبقوا سلاسل مختلفة حرفياً.
 * نفس المنطق كان مكرر في 4 ملفات استيراد على السيرفر — ده النسخة الموحّدة المشتركة.
 */
export function normalizeArabicKey(value: unknown): string {
  return String(value ?? "")
    .trim()
    .toLowerCase()
    .replace(/[ً-ٰٟ]/g, "")
    .replace(/ـ/g, "")
    .replace(/[أإآٱ]/g, "ا")
    .replace(/ى/g, "ي")
    .replace(/ة/g, "ه")
    .replace(/[\s\-_/\\]+/g, " ")
    .trim();
}
